export function buildUserPrompt(args: {
  channel: ChannelId;
  topic: string;
  theme: string;
  week: number;
  contentType: string;
  audience: Audience;
  maxChars: number;
}): string {
  const phase = plan.phases.find((p) => p.weeks.includes(args.week));
  return `اكتب منشورًا واحدًا وفق المواصفات التالية.

## القناة
${CHANNEL_BRIEF[args.channel]}
الحد الأقصى المطلق لطول الحقل body: ${args.maxChars} حرفًا.

## الموضوع
${args.topic}

## السياق
- الأسبوع ${args.week} من الخطة — محوره: ${args.theme}
- مرحلة الحملة: ${phase?.name ?? "—"} — هدفها: ${phase?.goal ?? "—"}
- ${TYPE_BRIEF[args.contentType] ?? ""}

## الجمهور المستهدف
- الشريحة: ${args.audience.name}
- وجعه الحقيقي: ${args.audience.pain}
- الرسالة المحورية التي يجب أن يخرج بها: ${args.audience.message}

## المطلوب
أعد كائنًا يحوي:
- hook: أول سطر أو سطرين يوقفان التمرير (مستقلان بذاتهما).
- body: النص الكامل للمنشور جاهزًا للنشر كما هو، متضمنًا الخطاف في بدايته، وبدون الوسوم.
- cta: دعوة الفعل في جملة واحدة.
- hashtags: مصفوفة وسوم بالعربية بدون رمز #.
- mediaBrief: وصف تنفيذي بالعربية للمصمم أو المصور عن الصورة أو الفيديو المطلوب (اللقطة، الألوان، النص على الشاشة). الهوية: أسود عميق وذهبي وكريمي مع زخرفة نجدية.`;
}
